function humanizeKey(key) {
	return String(key)
		.replace(/([a-z0-9])([A-Z])/g, "$1 $2")
		.replace(/[-_]+/g, " ")
		.replace(/^./, (character) => character.toUpperCase());
}

export function normalizeConfigPath(moduleKey, path = []) {
	return path.reduce(
		(result, segment) =>
			typeof segment === "number"
				? `${result}[]`
				: `${result}${result ? "." : ""}${segment}`,
		moduleKey,
	);
}

export function getFieldMeta(moduleKey, path, key) {
	const normalizedPath = normalizeConfigPath(moduleKey, path);
	const exact = pathMetadata[normalizedPath] ?? {};
	return {
		label: exact.label ?? fieldLabels[key] ?? humanizeKey(key || "配置项"),
		description: exact.description ?? fieldDescriptions[key] ?? "",
		technicalPath: normalizedPath,
		unit: exact.unit ?? units[key] ?? "",
	};
}

export function getEnumOptions(moduleKey, path) {
	return enumOptions[normalizeConfigPath(moduleKey, path)] ?? null;
}

function optionLabel(moduleKey, path, value) {
	return getEnumOptions(moduleKey, path)?.find(
		([optionValue]) => String(optionValue) === String(value),
	)?.[1];
}

export function getArrayItemMeta(moduleKey, path, item, index) {
	if (item === null || typeof item !== "object" || Array.isArray(item)) {
		return { title: `第 ${index + 1} 项`, detail: String(item ?? "") };
	}
	const normalizedPath = normalizeConfigPath(moduleKey, path);
	if (normalizedPath === "siteConfig.favicon") {
		return {
			title: `${item.theme === "dark" ? "深色" : "浅色"}图标 · ${item.sizes || "未标尺寸"}`,
			detail: item.src || "未填写文件",
		};
	}
	if (normalizedPath.includes("sidebarLayoutConfig.") && item.type) {
		return {
			title:
				optionLabel(moduleKey, [...path, index, "type"], item.type) ??
				item.type,
			detail: item.position ? `位置：${item.position}` : "侧边栏组件",
		};
	}
	const title =
		item.name ||
		item.title ||
		item.label ||
		item.id ||
		item.path ||
		`第 ${index + 1} 项`;
	let detail = item.url || item.siteurl || item.desc || item.description || "";
	if (Array.isArray(item.children))
		detail = `${item.children.length} 个子菜单${detail ? ` · ${detail}` : ""}`;
	if (Array.isArray(item.items))
		detail = `${item.items.length} 个项目${detail ? ` · ${detail}` : ""}`;
	return { title: String(title), detail: String(detail) };
}

export function getObjectTitle(moduleKey, path, key, value) {
	const meta = getFieldMeta(moduleKey, path, key);
	if (moduleKey === "LinkPresets" && path.length === 1 && value?.name) {
		return `${value.name}预设`;
	}
	return meta.label;
}
